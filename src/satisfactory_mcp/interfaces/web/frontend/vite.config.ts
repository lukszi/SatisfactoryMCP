/* The build, and the one thing about it that is not Vite's default: where it writes.
 *
 * The output directory IS the directory the Python package serves. `interfaces/web/app.py`
 * mounts `static/` at `/` and knows nothing about this project, so a build lands the page
 * exactly where the server expects to find it. The bundle is NOT committed: `static/` is
 * gitignored, because a dependency's compiled code -- Leaflet, minified, inside `app.js` --
 * has no business in this repository's tree. A fresh clone has no page until
 * `npm ci && npm run build` runs here once, and `app.py` says exactly that at `/` until
 * it has.
 *
 * `emptyOutDir` is on, and it is why nothing hand-written may live in `static/` any more.
 * Every file the server needs is produced here: the page from `index.html`, the bundle and
 * its stylesheet from `src/`, Leaflet's BSD-2-Clause text from the `leaflet` package
 * itself (the `leafletLicence` plugin below). A file dropped into `static/` by hand
 * survives exactly until the next build.
 */

import { readFileSync } from "node:fs";

import { defineConfig, type Plugin } from "vite";

/* Node's own global, declared rather than pulled in with `@types/node`. This file runs under
 * Node and the rest of `src/` runs in a browser; installing the Node types to satisfy one
 * line would put `require`, `Buffer` and `process` in scope for the whole program, where
 * every one of them is a mistake waiting to type-check. */
declare const process: { env: Record<string, string | undefined> };

/* Stamped into every generated file, and asserted by ``tests/test_architecture.py``.
 *
 * No timestamp and no version in it, deliberately: a rebuild from the same source should
 * produce the same bytes, so that two builds can be compared and neither is noise. What
 * the marker has to say is only "this file is output", and that sentence is the same
 * every time.
 *
 * The Leaflet line matters MORE now that the repository no longer redistributes Leaflet
 * at all -- the bundle is untracked, so the only Leaflet anyone can receive from here is
 * a build someone ran and then passed on, and that artifact has to carry its own notices.
 * The minifier strips the library's `@preserve` header, so the banner restores the
 * attribution: `vendor/LEAFLET-LICENSE` ships next to the bundle (copied out of the npm
 * package at build time, below), the page says so in a comment, and the artifact itself
 * names what is compiled into it. BSD-2-Clause asks for the notice to travel with the
 * binary form, and a reader who opens only this file should not have to go looking. */
const BANNER = [
  "GENERATED by Vite from src/satisfactory_mcp/interfaces/web/frontend/ -- do not edit.",
  "Edit the TypeScript there and run `npm ci && npm run build`; see frontend/README.md.",
  "Bundles Leaflet 1.9.4 (c) 2010-2023 Vladimir Agafonkin, (c) 2010-2011 CloudMade,",
  "BSD-2-Clause -- full text in vendor/LEAFLET-LICENSE beside this file.",
];

/* The marker, injected after minification rather than through `output.banner`.
 *
 * esbuild's minifier runs over the chunk and strips comments that are not legal comments,
 * and the exact interleaving of that pass with Rollup's banner hook is an implementation
 * detail this file should not be betting the guard test on. Writing the string into the
 * finished chunk in `generateBundle` is the one place nothing runs after. */
function banner(): Plugin {
  return {
    name: "build-banner",
    apply: "build",
    enforce: "post",
    generateBundle(_options, bundle) {
      for (const file of Object.values(bundle)) {
        if (file.type === "chunk") {
          file.code = `/* ${BANNER.join("\n * ")} */\n${file.code}`;
        } else if (file.fileName.endsWith(".css") && typeof file.source === "string") {
          file.source = `/* ${BANNER.join("\n * ")} */\n${file.source}`;
        }
      }
    },
    transformIndexHtml(html) {
      return `<!--\n  ${BANNER.join("\n  ")}\n-->\n${html}`;
    },
  };
}

/* Leaflet's licence text, copied out of the npm package into `vendor/LEAFLET-LICENSE`
 * beside the bundle.
 *
 * The source of truth is `node_modules/leaflet/LICENSE` -- the file the dependency itself
 * ships -- not a hand-vendored copy that could silently diverge from the version actually
 * compiled in. There used to be one, in `public/vendor/`; it is gone, and this hook is what
 * replaced it. Read at emit time rather than at config load so the failure, if the package
 * layout ever changes, happens inside the build with Rollup's file name attached.
 *
 * This is the self-compliance half of the licence posture: the repository no longer
 * redistributes Leaflet (the bundle is untracked -- that is the point), but every build
 * output remains a thing someone MAY distribute, and BSD-2-Clause requires the notice to
 * travel with the binary form when they do. So every build carries it, unconditionally. */
function leafletLicence(): Plugin {
  return {
    name: "leaflet-licence",
    apply: "build",
    generateBundle() {
      this.emitFile({
        type: "asset",
        fileName: "vendor/LEAFLET-LICENSE",
        source: readFileSync(new URL("./node_modules/leaflet/LICENSE", import.meta.url), "utf-8"),
      });
    },
  };
}

export default defineConfig({
  // Relative asset URLs, as the hand-written page used: the app is mounted at `/` today,
  // and a page whose own links do not depend on that is a page that survives being mounted
  // anywhere else.
  base: "./",
  plugins: [banner(), leafletLicence()],
  build: {
    outDir: "../static",
    emptyOutDir: true,
    // Stable names, no content hash. `tests/test_architecture.py` pins the exact contents
    // of `static/` by name, and a diff between two builds should say what changed, not
    // rename everything. Cache busting is `StaticFiles`' ETag instead, which revalidates
    // on a name that does not move.
    rollupOptions: {
      output: {
        entryFileNames: "app.js",
        chunkFileNames: "chunk-[name].js",
        assetFileNames: (info) =>
          info.names?.some((n) => n.endsWith(".css")) ? "app.css" : "assets/[name][extname]",
      },
    },
  },
  server: {
    proxy: {
      /* Everything the page fetches, straight through to a running `satisfactory-mcp-web`.
       *
       * `/api/events` is Server-Sent Events, so the one thing this must not do is buffer:
       * a proxy that collects a response body before forwarding it turns a live stream into
       * a page that hangs on the first save. Vite's proxy streams and adds no compression of
       * its own, which is why there is nothing to configure here -- and frontend/README.md
       * says how that was measured rather than assumed.
       *
       * The port is `satisfactory-mcp-web`'s own default. The override exists because the
       * server is sometimes already running somewhere else, and because pointing a dev
       * session at a throwaway instance beats pointing it at the one someone is playing
       * against. */
      "/api": {
        target: process.env.SATISFACTORY_MCP_WEB || "http://127.0.0.1:8712",
        changeOrigin: true,
        ws: false,
      },
    },
  },
});
