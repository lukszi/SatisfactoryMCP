/* The build writes the page into ../static/, the directory app.py serves at `/`. That output is
 * gitignored, so a fresh clone has no page until `npm ci && npm run build` runs here. emptyOutDir
 * is on, so nothing hand-written may live in static/. The why of each choice, the licence
 * included, is in frontend/README.md. */

import { readFileSync } from "node:fs";

import { defineConfig, type Plugin, type UserConfig } from "vite";

// Node's global, declared rather than installing @types/node (see node-fs.d.ts).
declare const process: { env: Record<string, string | undefined> };

// No timestamp or version, so two builds of one source are byte-identical.
function bannerLines(licence: string, elk: boolean): string[] {
  const lines = [
    "GENERATED by Vite from src/satisfactory_mcp/interfaces/web/frontend/ -- do not edit.",
    "Edit the TypeScript there and run `npm ci && npm run build`; see frontend/README.md.",
    "Bundles Leaflet 1.9.4 (c) 2010-2023 Vladimir Agafonkin, (c) 2010-2011 CloudMade,",
    "BSD-2-Clause -- full text in " + licence + " beside this file.",
  ];
  if (elk) {
    lines.push(
      "Bundles elkjs 0.11.1 (Eclipse Layout Kernel, (c) Kiel University, TypeFox and others), used under",
      "EPL-2.0 -- full text in " + ELK_LICENCE + "; " + ELK_WORKER + " is its unmodified worker."
    );
  }
  return lines;
}

// Stamps the banner into every emitted file after minification; tests/architecture/test_frontend_layout.py asserts it.
function banner(licence: string, elk: boolean): Plugin {
  const BANNER = bannerLines(licence, elk);
  return {
    name: "build-banner",
    apply: "build",
    enforce: "post",
    generateBundle(_options, bundle) {
      for (const file of Object.values(bundle)) {
        if (file.type === "chunk") {
          file.code = `/* ${BANNER.join("\n * ")} */\n${file.code}`;
        } else if (file.fileName.endsWith(".css") && typeof file.source === "string") {
          file.source = `/* ${BANNER.join("\n * ")} */\n${file.source}`;
        }
      }
    },
    transformIndexHtml(html) {
      return `<!--\n  ${BANNER.join("\n  ")}\n-->\n${html}`;
    },
  };
}

// Copies node_modules/leaflet/LICENSE beside the bundle, so every build carries the notice.
function leafletLicence(fileName: string): Plugin {
  return {
    name: "leaflet-licence",
    apply: "build",
    generateBundle() {
      this.emitFile({
        type: "asset",
        fileName: fileName,
        source: readFileSync(new URL("./node_modules/leaflet/LICENSE", import.meta.url), "utf-8"),
      });
    },
  };
}

/* elkjs ships its worker as a finished script: it is copied as it is, not bundled, so the
 * banner never touches it and its licence travels beside it. */
const ELK_LICENCE = "vendor/ELKJS-LICENSE";
const ELK_WORKER = "vendor/elk-worker.min.js";

function elkLicence(): Plugin {
  return {
    name: "elkjs-licence",
    apply: "build",
    generateBundle() {
      this.emitFile({
        type: "asset",
        fileName: ELK_LICENCE,
        source: readFileSync(new URL("./node_modules/elkjs/LICENSE.md", import.meta.url), "utf-8"),
      });
    },
  };
}

/* `--mode share`: the map-only page for a public static site (docs/map/sharing.md). Content-
 * hashed names so its scripts can be cached for a year, no source maps, and every file with an
 * extension a locked-down web server will serve. */
const SHARE_BUILD: UserConfig = {
  base: "./",
  plugins: [banner("vendor/LEAFLET-LICENSE.txt", false), leafletLicence("vendor/LEAFLET-LICENSE.txt")],
  build: {
    outDir: "dist-share",
    emptyOutDir: true,
    sourcemap: false,
    modulePreload: { polyfill: false },
    rollupOptions: {
      input: "share.html",
      output: {
        entryFileNames: "assets/app-[hash].js",
        chunkFileNames: "assets/chunk-[hash].js",
        assetFileNames: "assets/[name]-[hash][extname]",
      },
    },
  },
};

export default defineConfig(({ mode }) => (mode === "share" ? SHARE_BUILD : {
  // Relative asset URLs, so the page survives being mounted somewhere other than `/`.
  base: "./",
  plugins: [banner("vendor/LEAFLET-LICENSE", true), leafletLicence("vendor/LEAFLET-LICENSE"), elkLicence()],
  build: {
    outDir: "../static",
    emptyOutDir: true,
    // Stable names, no content hash: tests/architecture/test_frontend_layout.py pins static/ by name.
    rollupOptions: {
      output: {
        entryFileNames: "app.js",
        chunkFileNames: "chunk-[name].js",
        assetFileNames: (info) => {
          if (info.names?.some((n) => n.endsWith(".css"))) return "app.css";
          if (info.names?.some((n) => n === "elk-worker.min.js")) return ELK_WORKER;
          return "assets/[name][extname]";
        },
      },
    },
  },
  server: {
    proxy: {
      // /api to a running satisfactory-mcp-web; SSE streams through unbuffered (see README).
      "/api": {
        target: process.env.SATISFACTORY_MCP_WEB || "http://127.0.0.1:8712",
        changeOrigin: true,
        ws: false,
      },
    },
  },
}));
